  let EFF = MAP;
  function buildEff(){ EFF = Object.assign({}, MAP, (window.ZHUYIN_MAP || {})); }

  function isHan(ch){ const c = ch.charCodeAt(0); return c >= 0x4E00 && c <= 0x9FFF; }

  // 建立一個 <ruby> 元素
  function ruby(base, zy){
    const r = document.createElement("ruby");
    r.setAttribute("data-zy", "1");
    r.setAttribute("data-base", base);
    r.appendChild(document.createTextNode(base));
    const rt = document.createElement("rt");
    rt.textContent = zy;
    r.appendChild(rt);
    return r;
  }

  // 在 textNode 上做注音標示；vocabKeys 已依長度由長到短排序
  function annotateTextNode(node, vocab, vocabKeys){
    const text = node.nodeValue;
    const frag = document.createDocumentFragment();
    let i = 0, buffer = "";
    const flush = () => { if (buffer){ frag.appendChild(document.createTextNode(buffer)); buffer = ""; } };
    while (i < text.length){
      // 先試詞（vocab 權威覆蓋）
      let matched = null;
      for (const key of vocabKeys){
        if (key && text.startsWith(key, i)){ matched = key; break; }
      }
      if (matched){
        flush();
        const zys = String(vocab[matched]).trim().split(/\s+/);
        for (let k = 0; k < matched.length; k++){
          frag.appendChild(ruby(matched[k], zys[k] || ""));
        }
        i += matched.length;
        continue;
      }
      const ch = text[i];
      if (isHan(ch) && EFF[ch]){
        flush();
        frag.appendChild(ruby(ch, EFF[ch]));
      } else {
        buffer += ch;
      }
      i++;
    }
    flush();
    node.parentNode.replaceChild(frag, node);
  }

